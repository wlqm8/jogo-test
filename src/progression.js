export function questProgress(model, quest) {
  let progress;
  if (quest.metric === "dog" || quest.metric === "robot")
    progress = model.petLevels[quest.metric];
  else if (quest.metric === "buildings")
    progress = Object.values(model.buildings).reduce((a, b) => a + b, 0);
  else if (quest.metric === "level") progress = model.experience.level;
  else progress = model[quest.metric];
  return Math.min(quest.target, Math.max(0, progress));
}
